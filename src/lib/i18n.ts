import { EDGE_RELATIONS, KNOWLEDGE_REGIONS } from "@/lib/regions";
import { EdgeRelationType, RegionCode } from "@/types/knowledge";

export type Language = "en" | "id";
export type ThemeMode = "light" | "dark";

export function regionName(code: RegionCode, lang: Language): string {
  const reg = KNOWLEDGE_REGIONS[code] || KNOWLEDGE_REGIONS["REG-01"];
  return lang === "id" ? reg.nameId : reg.name;
}

export function regionShortName(code: RegionCode, lang: Language): string {
  const reg = KNOWLEDGE_REGIONS[code] || KNOWLEDGE_REGIONS["REG-01"];
  return lang === "id" ? reg.shortNameId : reg.shortName;
}

export function regionDescription(code: RegionCode, lang: Language): string {
  const reg = KNOWLEDGE_REGIONS[code] || KNOWLEDGE_REGIONS["REG-01"];
  return lang === "id" ? reg.description : reg.descriptionEn;
}

export function edgeShortLabel(type: EdgeRelationType, lang: Language): string {
  const rel = EDGE_RELATIONS[type] || EDGE_RELATIONS.extension;
  return lang === "id" ? rel.shortLabelId : rel.shortLabel;
}

export function edgeDescription(type: EdgeRelationType, lang: Language): string {
  const rel = EDGE_RELATIONS[type] || EDGE_RELATIONS.extension;
  return lang === "id" ? rel.description : rel.descriptionEn;
}

export function difficultyLabel(difficulty: string, lang: Language): string {
  if (lang === "en") return difficulty;
  const map: Record<string, string> = {
    Foundation: "Fondasi",
    Basic: "Dasar",
    Intermediate: "Menengah",
    Advanced: "Lanjut",
  };
  return map[difficulty] || difficulty;
}

